const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('gold', {
  getState: () => ipcRenderer.invoke('gold:state'),
  refresh: () => ipcRenderer.invoke('gold:refresh'),
  saveRules: (rules) => ipcRenderer.invoke('gold:save-rules', rules),
  setPrimary: (symbol) => ipcRenderer.invoke('gold:set-primary', symbol),
  setCalcSymbol: (symbol) => ipcRenderer.invoke('gold:set-calc-symbol', symbol),
  setPollSeconds: (seconds) => ipcRenderer.invoke('gold:set-interval', seconds),
  saveBark: (bark) => ipcRenderer.invoke('gold:save-bark', bark),
  barkTest: () => ipcRenderer.invoke('gold:bark-test'),
  saveWebhook: (config) => ipcRenderer.invoke('gold:save-webhook', config),
  webhookTest: (url) => ipcRenderer.invoke('gold:webhook-test', url),
  saveMail: (config) => ipcRenderer.invoke('gold:save-mail', config),
  mailTest: (config) => ipcRenderer.invoke('gold:mail-test', config),
  saveBot: (config) => ipcRenderer.invoke('gold:save-bot', config),
  botTest: (config) => ipcRenderer.invoke('gold:bot-test', config),
  saveDigest: (config) => ipcRenderer.invoke('gold:save-digest', config),
  saveQuiet: (config) => ipcRenderer.invoke('gold:save-quiet', config),
  getCapabilities: () => ipcRenderer.invoke('gold:capabilities'),
  setBall: (patch) => ipcRenderer.invoke('gold:set-ball', patch),
  setTaskbar: (patch) => ipcRenderer.invoke('gold:set-taskbar', patch),
  setDisplay: (patch) => ipcRenderer.invoke('gold:set-display', patch),
  setTrend: (patch) => ipcRenderer.invoke('gold:set-trend', patch),
  setOrder: (symbols) => ipcRenderer.invoke('gold:set-order', symbols),
  setLaunchAtLogin: (enabled) => ipcRenderer.invoke('gold:set-launch-at-login', enabled),
  openDashboard: () => ipcRenderer.invoke('gold:open-dashboard'),
  londonConvert: (args) => ipcRenderer.invoke('gold:convert-london', args),
  calcLoad: (args) => ipcRenderer.invoke('calc:load', args),
  calcAdd: (args) => ipcRenderer.invoke('calc:add', args),
  calcRemove: (args) => ipcRenderer.invoke('calc:remove', args),
  calcSaveFees: (args) => ipcRenderer.invoke('calc:save-fees', args),
  calcSummary: (args) => ipcRenderer.invoke('calc:summary', args),
  quit: () => ipcRenderer.send('gold:quit'),
  notifyTest: () => ipcRenderer.send('gold:notify-test'),
  onUpdate: (callback) => ipcRenderer.on('gold:update', (_event, state) => callback(state)),
  onMode: (callback) => ipcRenderer.on('panel:mode', (_event, mode) => callback(mode)),
});
